    private static readonly Dictionary<string, int> ByNameLookup = BuildNameLookup();

    private static Dictionary<string, int> BuildNameLookup()
    {
        var map = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var (number, entry) in ByNumber)
        {
            map.TryAdd(entry.Name, number);
        }

        return map;
    }

    public static Entry EntryOf(int number)
        => ByNumber.TryGetValue(number, out var e) ? e : ByNumber[DefaultNumber];

    public static bool TryGetNumberByName(string name, out int number)
        => ByNameLookup.TryGetValue(name, out number);
